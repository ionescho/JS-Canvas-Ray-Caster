const rgbToGrayscale = (red: number, green: number, blue: number) => {
    const r = red * .3 // ------> Red is low
    const g = green * .59 // ---> Green is high
    const b = blue * .11 // ----> Blue is very low

    const gray = r + g + b

    return gray;
}

const parseTextureArrayFromImage: (imageConfig: ImageConfig) => Promise<ParsedWallTexture> =  (imageConfig) => {
    return new Promise((resolve) => {
        let img = new Image();
        img.src = imageConfig.source as string;
        img.onload = () => {
            let canvas = document.createElement('canvas');
            canvas.setAttribute('width', `${img.width}px`);
            canvas.setAttribute('height', `${img.height}px`);// 1. Initialize context with the willReadFrequently attribute
            const context = canvas.getContext('2d', { willReadFrequently: true }) as CanvasRenderingContext2D;

            context.drawImage(img, 0, 0);
            const result: number[][] | number[][][] = [];

            // 2. Optimization: Get all image data at once to avoid repeated GPU-to-CPU overhead
            const fullImageData = context.getImageData(0, 0, img.width, img.height).data;

            const resX = imageConfig.resolutionX as number;
            const resY = imageConfig.resolutionY as number;

            for(var y = 0; y < resY; y++) {
                result.push([]);
                const imageY = Math.floor(y / resY * img.height);
                for(var x = 0; x < resX; x++) {
                    const imageX = Math.floor(x / resX * img.width);
                    
                    // Calculate the index in the flat Uint8ClampedArray (r, g, b, a)
                    const index = (imageY * img.width + imageX) * 4;
                    const r = fullImageData[index];
                    const g = fullImageData[index + 1];
                    const b = fullImageData[index + 2];
                    if(imageConfig.grayscale) {
                        const divisor = 256 / imageConfig.grayscale.depth;
                        result[y][x] = Math.round(rgbToGrayscale(r, g, b) / divisor) * divisor;
                    } else {
                        result[y][x] = [r, g, b];

                    }
                }
            }
            resolve(result);
        }
    })
}

const parseImageBitmapStripsFromImage: (imageConfig: ImageConfig) => Promise<ImageBitmap[]> =  (imageConfig) => {
    return new Promise((resolve) => {
        let img = new Image();
        img.src = imageConfig.source as string;
        img.onload = async () => {
            const imageWidth = img.width;
            const imageBitmapStripsArray: ImageBitmap[] = [];

            for(var i = 0; i < imageWidth; i++) {
                imageBitmapStripsArray.push(await createImageBitmap(img, i, 0, 1, img.height));
            }
            resolve(imageBitmapStripsArray);
        }
    })
}

export const wallTextures: ParsedWallTexture[] = [];

export const parseWallTextureConfig = async () => {
    for(var textureConfig of wallTexturesConfig ) {
        let parsedTextureConfig: ParsedWallTexture;
        if(!(textureConfig.source instanceof Array)) {
            if(textureConfig.useImageBitmapStrips) {
                parsedTextureConfig = await parseImageBitmapStripsFromImage(textureConfig);
            } else {
                parsedTextureConfig = await parseTextureArrayFromImage(textureConfig);
            }
        } else {
            parsedTextureConfig = textureConfig.source;
        }
        wallTextures.push(parsedTextureConfig)
    }
}